/**
 * Where a company-history report came from, in words a reader can act on. None of these sources is fact-checked;
 * the label says how much to trust the narrative, not the live price/news blocks (which are sourced separately).
 */
export type HistorySource = "hardcoded" | "ai-generated" | "sector-playbook" | "fallback";

export interface Provenance {
  label: string;
  detail: string;
  /** "caution" sources are shown with a visible banner. */
  level: "info" | "caution";
}

export function historyProvenance(source: HistorySource | undefined): Provenance {
  switch (source) {
    case "hardcoded":
      return { label: "Hand-written summary", detail: "Written by the EquityLens team for a few large companies. Not independently verified; check filings before relying on any figure.", level: "info" };
    case "ai-generated":
      return { label: "AI-written, not fact-checked", detail: "Generated by a language model from its general knowledge and recent headlines. It can contain wrong dates, figures or events.", level: "caution" };
    case "sector-playbook":
      return { label: "Sector template", detail: "A generic narrative for companies in this sector, not a history of this company.", level: "caution" };
    default:
      return { label: "Generic template", detail: "No company-specific history was available; this is a placeholder narrative.", level: "caution" };
  }
}
